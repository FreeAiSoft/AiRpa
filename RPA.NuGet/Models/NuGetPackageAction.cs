namespace RPA.NuGet.Models
{
    /// <summary>
    /// Действие большой кнопки в панели деталей. Набор и приоритет — как в менеджере пакетов
    /// Visual Studio 2026: у неподключённого пакета кнопка ставит версию, у подключённого —
    /// обновляет/понижает её, а на выбранной установленной версии предлагает удаление.
    /// </summary>
    public enum NuGetPackageAction
    {
        /// <summary>Действие не определено (нет выбранной версии).</summary>
        None = 0,

        Install = 1,

        Update = 2,

        Downgrade = 3,

        Uninstall = 4
    }
}
