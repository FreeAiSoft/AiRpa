namespace LogControlLibrary.Configuration
{
    /// <summary>
    /// Предустановленные профили производительности для виртуализации логов
    /// </summary>
    public enum PerformanceProfile
    {
        /// <summary>
        /// Профиль для систем с ограниченной памятью
        /// - Малые размеры страниц и кэша
        /// - Включено сжатие данных
        /// - Минимальная предзагрузка
        /// </summary>
        LowMemory,

        /// <summary>
        /// Сбалансированный профиль (рекомендуется по умолчанию)
        /// - Оптимальное соотношение памяти и производительности
        /// - Умеренные размеры страниц и кэша
        /// - Включена индексация
        /// </summary>
        Balanced,

        /// <summary>
        /// Профиль для максимальной производительности
        /// - Большие размеры страниц и кэша
        /// - Агрессивная предзагрузка
        /// - Все оптимизации включены
        /// </summary>
        HighPerformance,

        /// <summary>
        /// Пользовательские настройки
        /// - Ручная настройка всех параметров
        /// - Не применяет автоматические изменения
        /// </summary>
        Custom
    }
}